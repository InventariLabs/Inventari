from typing import Literal, NotRequired, TypedDict, cast, get_args

Language = Literal['en', 'pl', 'de', 'fr', 'es', 'pt']

#: The set of languages the backend speaks. Derived from the `Language`
#: literal above — that literal is the single source of truth, and every
#: other place that needs the set reads it from here (or from
#: `app.i18n.SUPPORTED_LANGUAGES`, the same object) instead of keeping a
#: copy of its own. A hand-kept second list is what drifts when a language
#: is added.
SUPPORTED_LANGUAGES: tuple[Language, ...] = cast(
    'tuple[Language, ...]', get_args(Language)
)

#: The languages that may ship below full coverage. Every other language is
#: maintained: a change brings all of them and the gates require the full
#: set. A community language is written by whoever speaks it, catches up in
#: batches, and answers in English for any key it has not got yet — no change
#: has to translate it. The frontend declares the same split in
#: `frontend/src/i18n/languages.ts`; a parity gate holds the two together.
COMMUNITY_LANGUAGES: tuple[Language, ...] = ('pt',)

#: The languages every change must carry in full: what the gates, the parity
#: tests next to a module's catalogs and the stock error catalog require.
MAINTAINED_LANGUAGES: tuple[Language, ...] = tuple(
    language for language in SUPPORTED_LANGUAGES if language not in COMMUNITY_LANGUAGES
)


