def get_po_labels(lang: str) -> dict[str, str]:
    """PO-specific template labels for *lang* (i18n-lite, English fallback).

       Shared by the PDF generator and the HTML preview endpoint so both render
    the same labels.
    """
    return _svc.get_labels(lang)


async def generate_po_pdf(
    po: PurchaseOrder,
    lang: str = 'en',
    db: AsyncSession | None = None,
    org_id: uuid.UUID | None = None,
) -> bytes:
    # The single context builder shared with the HTML preview endpoint
    # (_po_render_context.build_po_context) — the two used to be separate
    # builders that drifted apart (tax_pct only in the PDF, po_title only in
    # the preview). Lazy import: _po_render_context imports get_po_labels
    # from this module, so a module-level import here would be circular.
    from ._po_render_context import build_po_context

    # The letterhead the shared header prints. An order used to print
    # a bare organization name where a warehouse document printed the full
    # issuer identity — the same fact, told twice, differently.
    issuer = await build_issuer_context(po.organization, lang)
    context = build_po_context(po, lang, issuer)

    html_content: str | None = None
    if db is not None and org_id is not None:
        html_content = await _svc.try_db_template(
            db,
            org_id,
            context,
            document_type='STANDARD',
        )

    if html_content is None:
        html_content = _svc.render_filesystem_template('po_standard.html', context)
        logger.debug('Generating PDF for PO %s using filesystem template', po.id)

    # The paper the organization prints on — stated after the body, so
    # whatever a template said about page size loses to it. Read through
    # the column query: ``po.organization`` may be an instance whose
    # deferred page-size column was never loaded.
    if db is not None and org_id is not None:
        page_size = await resolve_page_size_async(db, org_id)
    else:
        page_size = page_size_of(po.organization)
    page = apply_page_size(html_content, page_size)
    # WeasyPrint is synchronous and CPU-bound: keep it off the event loop.
    # (to_thread carries the request's context variables along, like the
    # core helper the modules may not import.)
    return await asyncio.to_thread(_svc.render_to_pdf, page)
