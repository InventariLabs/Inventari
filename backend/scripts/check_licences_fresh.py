"""Fail when THIRD_PARTY_LICENSES.md no longer matches the declared runtime.

The full report is generated by ``manage.py audit scan-dependencies --write``,
which needs an installed backend venv *and* a frontend node_modules tree in the
same checkout. CI has both; a container-based local gate has neither, which is
how a dependency change once shipped with a stale report — the file still
listed a GPL system package for a tool that had been removed, and four Python
packages that were no longer installed anywhere.

This checks the part that needs no installation, by reading four files and
listing one directory:

* every direct runtime dependency in ``pyproject.toml`` must appear in the
  report's backend table — catches a dependency added without regenerating;
* every package in that table must still exist in ``uv.lock`` — catches a
  dependency removed without regenerating, transitive ones included;
* the version each row quotes must be the one ``uv.lock`` resolved — catches a
  dependency bumped without regenerating, which the name-only comparison let
  through while the reader was told a number that was no longer true;
* the frontend table must be exactly the production packages
  ``frontend/package-lock.json`` resolves, at the versions it quotes — rows
  the lock no longer resolves and production packages with no row, a half no
  gate at commit time could watch, because the hook did not fire on that
  lockfile;
* every directory under ``frontend/public`` must have a row in the report's
  assets table, and every asset row must name a directory that still ships —
  catches a bundled asset added or removed without regenerating, which is how
  the Fluent Emoji files and the AI-provider logos shipped with no entry at all;
* every ``image:`` the compose files pull must have a row in the report's
  container-image table at the same tag, and every row there must still be
  pulled — catches an image bumped, added or dropped in a compose file while
  the hand-kept table kept describing the old stack;
* every system package named in the "system layer" table must still appear in
  one of the Dockerfiles — catches the row of a tool that was taken out.

Known gap: a package moved from the runtime set to the dev group stays in the
lock, so only the full generator notices it. Catching that here would mean
resolving the lock graph, which is the generator's job. On the frontend side
the mirror gap is a package the lock marks platform-conditional
(``optional: true``, fsevents on macOS): it is never demanded of the report,
because the machine the report was generated on may not have installed it.

Runs on the host with the standard library only, because the report lives
above the backend directory the container mounts.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
PYPROJECT = BACKEND_DIR / 'pyproject.toml'
LOCK = BACKEND_DIR / 'uv.lock'
REPORT = REPO_ROOT / 'THIRD_PARTY_LICENSES.md'
FRONTEND_LOCK = REPO_ROOT / 'frontend' / 'package-lock.json'
PUBLIC_DIR = REPO_ROOT / 'frontend' / 'public'
ASSET_SECTION = '## Bundled frontend assets'
FRONTEND_SECTION = '## Frontend production bundle'
IMAGE_SECTION = '## Container images'
SYSTEM_SECTION = '## Backend and backup images'

REGENERATE = (
    'Regenerate it from a checkout with both trees installed:\n'
    '  cd backend && uv run python manage.py audit scan-dependencies --write'
)

# "torch>=2.1,<3" / "uvicorn[standard]>=0.30" -> "torch" / "uvicorn"
_REQUIREMENT_NAME = re.compile(r'^([A-Za-z0-9._-]+)')
# "| `aioboto3` | 15.5.0 | Apache-2.0 |  |"
_REPORT_ROW = re.compile(r'^\|\s*`([^`]+)`\s*\|\s*([^|]*?)\s*\|')
# "    image: valkey/valkey:9.1.2-alpine" -> "valkey/valkey:9.1.2-alpine"
_COMPOSE_IMAGE = re.compile(r'^\s*image:\s*[\'"]?([^\s\'"#]+)', re.MULTILINE)


def _normalise(name: str) -> str:
    return name.lower().replace('_', '-')


def _declared_runtime_names() -> set[str]:
    data = tomllib.loads(PYPROJECT.read_text(encoding='utf-8'))
    names = set()
    for requirement in data['project']['dependencies']:
        match = _REQUIREMENT_NAME.match(requirement.strip())
        if match:
            names.add(_normalise(match.group(1)))
    return names


def _locked_versions(locked_path: Path = LOCK) -> dict[str, str]:
    """Normalised package name -> the version ``uv.lock`` resolved."""
    data = tomllib.loads(locked_path.read_text(encoding='utf-8'))
    return {
        _normalise(package['name']): str(package.get('version') or '')
        for package in data.get('package', [])
    }


def _reported_backend_rows(report_path: Path = REPORT) -> dict[str, tuple[str, str]]:
    """Normalised name -> (name as printed, version) from the backend table.

    The name travels as printed so a refusal can quote the row the reader is
    looking at, rather than the spelling the lock happens to use.
    """
    rows: dict[str, tuple[str, str]] = {}
    in_section = False
    for line in report_path.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            in_section = line.startswith('## Backend runtime')
            continue
        if not in_section:
            continue
        match = _REPORT_ROW.match(line)
        if match:
            name, version = match.group(1), match.group(2).strip()
            rows[_normalise(name)] = (name, version)
    return rows


def _reported_frontend_rows(report_path: Path = REPORT) -> set[tuple[str, str]]:
    """(name, version) of every row in the frontend table, as printed.

    Rows travel as pairs, not as a mapping: npm installs two versions of one
    package at different depths and the report lists both, so a name-keyed
    mapping would let one row hide the other. npm names are lowercase by
    rule, so the spelling the comparison needs is the one the table prints.
    """
    rows: set[tuple[str, str]] = set()
    in_section = False
    for line in report_path.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            in_section = line.startswith(FRONTEND_SECTION)
            continue
        if not in_section:
            continue
        match = _REPORT_ROW.match(line)
        if match:
            rows.add((match.group(1), match.group(2).strip()))
    return rows


def _reported_asset_rows(report_path: Path = REPORT) -> dict[str, str]:
    """Directory name under ``frontend/public`` -> the assets row as printed.

    Rows name the directory as ``frontend/public/<directory>``, and the lookup
    is scoped to the assets section so a package row can never satisfy the
    coverage check by accident. The row travels whole because the notice the
    entry has to carry (the MIT copyright line, the trademark sentence) is
    read off the printed line.
    """
    rows: dict[str, str] = {}
    in_section = False
    for line in report_path.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            in_section = line.startswith(ASSET_SECTION)
            continue
        if not in_section:
            continue
        match = _REPORT_ROW.match(line)
        if match:
            rows[Path(match.group(1)).name] = line
    return rows


def _section_rows(report_path: Path, heading: str) -> list[tuple[str, str]]:
    """(name, version) of every row in the section whose heading starts so."""
    rows: list[tuple[str, str]] = []
    in_section = False
    for line in report_path.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            in_section = line.startswith(heading)
            continue
        if not in_section:
            continue
        match = _REPORT_ROW.match(line)
        if match:
            rows.append((match.group(1), match.group(2).strip()))
    return rows


def reported_images(report_path: Path = REPORT) -> set[str]:
    """The image references the container-image table describes.

    A row names the reference with its tag (``valkey/valkey:9.1.2-alpine``)
    or, when the tag is the version column, without it (``rclone/rclone`` and
    ``1.75.1``); either way the reference a compose file pulls is rebuilt.
    """
    return {
        name if ':' in name else f'{name}:{version}'
        for name, version in _section_rows(report_path, IMAGE_SECTION)
    }


def compose_images(root: Path = REPO_ROOT) -> set[str]:
    """Every literal ``image:`` the compose files at the repository root pull.

    A reference built from a variable names nothing the report could quote, so
    it is left out rather than guessed at.
    """
    images: set[str] = set()
    for compose in sorted(root.glob('docker-compose*.yml')):
        for image in _COMPOSE_IMAGE.findall(compose.read_text(encoding='utf-8')):
            if '${' not in image:
                images.add(image)
    return images


def image_coverage_gaps(
    reported: set[str], pulled: set[str]
) -> tuple[list[str], list[str]]:
    """(images pulled with no row at that tag, rows naming an image nobody pulls)."""
    return sorted(pulled - reported), sorted(reported - pulled)


_COMMENT_LINE = re.compile(r'[ \t]*#')
_DIRECTIVE = re.compile(r'#\s*([A-Za-z]+)\s*=\s*(\S+)\s*$')
_HEREDOC = re.compile(r'(?<!<)<<(?!<)(-?)\s*(["\']?)([A-Za-z_]\w*)\2')
_RUN = re.compile(r'\s*RUN\b', re.IGNORECASE)
_PLAIN_COMMENT = re.compile(r'#[\w \t.,:/@%+=#-]*')
_OPERATORS = frozenset(';&|()')
_UNFOLLOWED = re.compile(r"\$[({']|`")


def _instructions(text: str) -> list[str]:
    """The Dockerfile's instructions, each read the way Docker reads it.

    A line ending in the escape character (``\\``, or the one an ``escape``
    parser directive names) runs on into the next, the two joined without the
    escape; a whole-line comment and, inside a continuation, an empty line are
    dropped, whatever they hold. A heredoc body belongs to its instruction
    verbatim up to its delimiter, comment-looking lines included: those are
    the shell's to read, not Docker's.
    """
    lines = text.splitlines()
    escape = '\\'
    for line in lines:
        directive = _DIRECTIVE.match(line)
        if not directive:
            break
        if directive[1].lower() == 'escape':
            escape = directive[2]
    continuation = re.compile(rf'{re.escape(escape)}[ \t]*$')
    instructions: list[str] = []
    current = ''
    continued = False
    heredocs: list[tuple[str, bool]] = []
    for line in lines:
        if heredocs:
            current += '\n' + line
            delimiter, strip_tabs = heredocs[0]
            if (line.lstrip('\t') if strip_tabs else line) == delimiter:
                heredocs.pop(0)
        elif _COMMENT_LINE.match(line) or (continued and not line.strip()):
            continue
        else:
            joined = continuation.sub('', line)
            continued = joined != line
            current += joined
            if not continued:
                heredocs = [(m[3], m[1] == '-') for m in _HEREDOC.finditer(current)]
        if current and not continued and not heredocs:
            instructions.append(current)
            current = ''
    if current:
        instructions.append(current)
    return instructions


def _without_comments(command: str) -> str:
    """One ``RUN`` instruction with its shell comments cut out.

    A comment is a ``#`` that starts a word outside quotes, up to the end of
    its line; a word starts after whitespace or a command operator (``;``,
    ``&``, ``|``, ``(``, ``)``), so ``add pkg;# note`` is a comment too.
    ``https://host/dl#frag`` and ``"a # b"`` keep their ``#``. A
    backslash escapes the next character outside single quotes, so
    ``"a \\" # b"`` is still quoted and ``a\\ #b`` one word; before a newline
    it only continues the line.

    This reader follows quotes and escapes, and nothing else of the shell. A
    ``#`` inside anything else is not a comment: an expansion (``${X:- #}``,
    ``$(...)``, backticks), whose closing bracket then sits in what looks
    like the comment, or a shell heredoc, whose lines are data. ANSI-C
    quoting (``$'it\\'s'``) ends where this reader does not. Before the first
    of those constructs the reading is exact, so a comment there is cut
    whatever it holds (``# age isn't installed``); after one, only a comment
    of plain words is. Any other comment, or any comment in an instruction
    with a shell heredoc, keeps the instruction whole, as does an instruction
    other than ``RUN``: a stale row kept alive costs less than a real install
    read as a comment.
    """
    first, _, body = command.partition('\n')
    if not _RUN.match(command) or '<<' in _HEREDOC.sub('', first) + body:
        return command
    out: list[str] = []
    quote = ''
    escaped = False
    word_start = True
    i = 0
    while i < len(command):
        char = command[i]
        if escaped:
            escaped = False
            if char != '\n':
                word_start = False
        elif char == '\\' and quote != "'":
            escaped = True
        elif quote:
            if char == quote:
                quote = ''
        elif char in '"\'':
            quote = char
            word_start = False
        elif char == '#' and word_start:
            end = command.find('\n', i)
            end = len(command) if end < 0 else end
            if not _PLAIN_COMMENT.fullmatch(command, i, end) and (
                _UNFOLLOWED.search(command, 0, i)
            ):
                return command
            i = end
            continue
        else:
            word_start = char.isspace() or char in _OPERATORS
        out.append(char)
        i += 1
    return ''.join(out)


def system_packages_gone(
    report_path: Path = REPORT, root: Path = REPO_ROOT
) -> list[str]:
    """System-layer rows none of whose packages any Dockerfile still names.

    A row may name several packages (``libpango / libcairo``); it stands while
    any one of them is still installed or fetched by some Dockerfile. A comment
    installs nothing, so it is not read.
    """
    text = '\n'.join(
        _without_comments(instruction)
        for path in sorted(root.rglob('Dockerfile*'))
        if 'node_modules' not in path.parts
        for instruction in _instructions(path.read_text(encoding='utf-8'))
    )
    gone = []
    for name, _version in _section_rows(report_path, SYSTEM_SECTION):
        tokens = [t.strip() for t in name.split('/') if t.strip()]
        if not any(
            re.search(rf'(?<![\w-]){re.escape(t)}(?![A-Za-z0-9_])', text)
            for t in tokens
        ):
            gone.append(name)
    return sorted(gone)


def bundled_asset_directories(public_dir: Path = PUBLIC_DIR) -> set[str]:
    """Directory names directly under ``frontend/public``."""
    return {path.name for path in public_dir.iterdir() if path.is_dir()}


def asset_coverage_gaps(
    reported: set[str], directories: set[str]
) -> tuple[list[str], list[str]]:
    """(directories with no row, rows naming no directory), each sorted."""
    return sorted(directories - reported), sorted(reported - directories)


def version_mismatches(
    reported: dict[str, tuple[str, str]], locked: dict[str, str]
) -> list[str]:
    """Rows whose quoted version is not the one ``uv.lock`` resolved.

    A package the lock does not hold at all is somebody else's complaint —
    the departure check names it — so it is left alone here rather than
    reported twice for one problem. A lock entry with no version is the same
    silence: nothing to compare against.
    """
    problems = []
    for key in sorted(reported):
        shown, version = reported[key]
        locked_version = locked.get(key)
        if not locked_version or locked_version == version:
            continue
        problems.append(
            f'{shown}: report says {version}, uv.lock says {locked_version}'
        )
    return problems


def _locked_frontend_packages(
    locked_path: Path = FRONTEND_LOCK,
) -> tuple[set[tuple[str, str]], set[tuple[str, str]]]:
    """The production packages ``package-lock.json`` resolves.

    Returns every ``(name, version)`` pair, and the platform-conditional
    ones among them. Dev-only entries (``"dev": true``) are left out: the
    report's frontend table is ``npm ls --omit=dev``, the production tree
    only, while the lockfile holds the development half as well. An entry's
    key is its path and its name comes from the entry, falling back to the
    last segment of the path — which is how npm spells it in ``npm ls`` too.
    """
    data = json.loads(locked_path.read_text(encoding='utf-8'))
    packages: set[tuple[str, str]] = set()
    conditional: set[tuple[str, str]] = set()
    for key, entry in data.get('packages', {}).items():
        if not key or 'node_modules/' not in key:
            continue  # the root manifest, which installs nothing
        version = entry.get('version')
        if entry.get('dev') or not version:
            continue
        name = entry.get('name') or key.split('node_modules/')[-1]
        packages.add((name, str(version)))
        if entry.get('optional'):
            conditional.add((name, str(version)))
    return packages, conditional


def frontend_row_problems(
    reported: set[tuple[str, str]], locked: set[tuple[str, str]]
) -> list[str]:
    """Rows the production lock does not resolve, each named with its answer.

    A name the lock does not hold at all is the departure; a name it resolves
    at other versions is the drift. Either way one row is one complaint
    quoting what the report says and what the lock holds, the pairing the
    backend table's version check makes.
    """
    by_name: dict[str, set[str]] = {}
    for name, version in locked:
        by_name.setdefault(name, set()).add(version)
    problems = []
    for name, version in sorted(reported):
        locked_versions = by_name.get(name)
        if not locked_versions:
            problems.append(
                f'{name}: report says {version}, package-lock.json lists no '
                'such package'
            )
        elif version not in locked_versions:
            problems.append(
                f'{name}: report says {version}, package-lock.json says '
                + ' or '.join(sorted(locked_versions))
            )
    return problems


def frontend_coverage_gaps(
    reported: set[tuple[str, str]],
    locked: set[tuple[str, str]],
    conditional: set[tuple[str, str]] = frozenset(),
) -> list[str]:
    """Production packages the lock resolves that the report does not list.

    The platform-conditional ones are left out: fsevents only installs on
    macOS, so the report — generated wherever the tree is built — may well
    hold no row for it, and demanding one would fail every commit on the
    platform the deployment is not.
    """
    return sorted(
        f'{name}@{version}' for name, version in (locked - conditional) - reported
    )


def frontend_table_complaints(
    reported: set[tuple[str, str]], locked_path: Path = FRONTEND_LOCK
) -> list[tuple[str, list[str]]]:
    """(complaint, names) for the frontend half — empty when the table stands.

    Both comparisons travel together because the caller prints them the way
    every other group is printed: one refusal per comparison, then the
    regenerate hint. The lockfile is read here, beside the reading the
    backend half does, so no state of the frontend's has to live in the
    caller.
    """
    locked, conditional = _locked_frontend_packages(locked_path)
    complaints: list[tuple[str, list[str]]] = []
    stale = frontend_row_problems(reported, locked)
    if stale:
        complaints.append(
            (
                'these frontend rows are not packages package-lock.json '
                'resolves for production',
                stale,
            )
        )
    missing = frontend_coverage_gaps(reported, locked, conditional)
    if missing:
        complaints.append(
            ('these production packages have no row in the frontend table', missing)
        )
    return complaints


def _complain(problem: str, names: list[str]) -> None:
    print(
        f'THIRD_PARTY_LICENSES.md is stale — {problem}:\n  '
        + '\n  '.join(names)
        + f'\n{REGENERATE}',
        file=sys.stderr,
    )


def main() -> int:
    for path in (PYPROJECT, LOCK, REPORT, FRONTEND_LOCK, PUBLIC_DIR):
        if not path.exists():
            print(f'{path} is missing.', file=sys.stderr)
            return 1

    reported_rows = _reported_backend_rows()
    reported = set(reported_rows)
    if not reported:
        print(
            'No "## Backend runtime" table found in THIRD_PARTY_LICENSES.md — '
            'the report format changed and this check needs updating.',
            file=sys.stderr,
        )
        return 1

    frontend_rows = _reported_frontend_rows()
    if not frontend_rows:
        print(
            'No "## Frontend production bundle" table found in '
            'THIRD_PARTY_LICENSES.md — the report format changed and this '
            'check needs updating.',
            file=sys.stderr,
        )
        return 1

    declared = _declared_runtime_names()
    locked = _locked_versions()
    failed = False

    unlisted = sorted(declared - reported)
    if unlisted:
        _complain('these runtime dependencies are declared but not listed', unlisted)
        failed = True

    departed = sorted(reported - set(locked))
    if departed:
        _complain('these listed packages are no longer in uv.lock', departed)
        failed = True

    drifted = version_mismatches(reported_rows, locked)
    if drifted:
        _complain('these listed versions differ from uv.lock', drifted)
        failed = True

    for complaint, names in frontend_table_complaints(frontend_rows):
        _complain(complaint, names)
        failed = True

    asset_rows = _reported_asset_rows()
    missing_assets, stale_assets = asset_coverage_gaps(
        set(asset_rows), bundled_asset_directories()
    )
    if missing_assets:
        _complain(
            'these directories under frontend/public have no entry in the report',
            missing_assets,
        )
        failed = True
    if stale_assets:
        _complain(
            'these report entries name directories that no longer ship',
            stale_assets,
        )
        failed = True

    unlisted_images, stale_images = image_coverage_gaps(
        reported_images(), compose_images()
    )
    if unlisted_images:
        _complain(
            'these images are pulled by a compose file but have no row at that tag '
            'in the container-image table',
            unlisted_images,
        )
        failed = True
    if stale_images:
        _complain(
            'these container-image rows name an image no compose file pulls',
            stale_images,
        )
        failed = True

    gone = system_packages_gone()
    if gone:
        _complain(
            'these system-layer rows name packages no Dockerfile mentions any more',
            gone,
        )
        failed = True

    if failed:
        return 1

    print(
        f'licences: {len(reported)} listed packages match pyproject and the lock; '
        f'{len(frontend_rows)} match package-lock.json; '
        f'{len(asset_rows)} asset directories and {len(reported_images())} '
        'container images covered.'
    )
    return 0


if __name__ == '__main__':
    sys.exit(main())
