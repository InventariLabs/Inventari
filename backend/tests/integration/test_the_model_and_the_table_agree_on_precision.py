"""Every exact column is as wide in the table as the model says it is.

A model that declares ``Numeric(10, 2)`` over a column the migrations left
as bare ``numeric`` makes two promises: the test databases, built from the
model, refuse a third decimal that production would happily store, and the
next autogenerated migration offers to narrow production down to the
model's word. ``items.quantity`` had exactly that gap and it was closed by
hand; ``items.purchase_price`` had the same one and nobody looked. So this
does not look at one column — it migrates a database of its own to head and
compares every numeric column of every core table against the model.
"""

from __future__ import annotations

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import Float, Numeric, create_engine, inspect

from app.core.db_isolation import isolated_db_url

pytestmark = pytest.mark.integration


def _numeric_shape(column_type: object) -> tuple[int | None, int | None] | None:
    """``(precision, scale)`` for an exact type, ``None`` for anything else.

    A double is a ``Numeric`` to SQLAlchemy and reflects with the 53 bits of
    its mantissa as "precision"; it has no decimal width to agree on.
    """
    inner = getattr(column_type, 'impl', column_type)
    if not isinstance(inner, Numeric) or isinstance(inner, Float):
        return None
    return (inner.precision, inner.scale)


def test_every_numeric_column_is_as_wide_as_the_model_declares(monkeypatch):
    import app.core.template_models
    import app.models  # noqa: F401
    from app.database import Base

    with isolated_db_url('precision') as url:
        monkeypatch.setenv('DATABASE_URL', url)
        command.upgrade(Config('alembic.ini'), 'head')

        engine = create_engine(url)
        inspector = inspect(engine)
        migrated_tables = set(inspector.get_table_names())

        disagreements: list[str] = []
        for table in Base.metadata.sorted_tables:
            # Module tables come from module migrations, which this does
            # not run; the core chain is the one under test.
            if table.name not in migrated_tables:
                continue
            in_db = {c['name']: c['type'] for c in inspector.get_columns(table.name)}
            for column in table.columns:
                declared = _numeric_shape(column.type)
                if declared is None or column.name not in in_db:
                    continue
                actual = _numeric_shape(in_db[column.name])
                if actual != declared:
                    disagreements.append(
                        f'{table.name}.{column.name}: model {declared}, table {actual}'
                    )
        engine.dispose()

    assert not disagreements, '\n'.join(disagreements)
