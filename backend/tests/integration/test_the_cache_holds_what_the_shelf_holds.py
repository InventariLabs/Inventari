"""A record can hold as large a quantity as the shelf it stands on.

``Item.quantity`` was a cache of the quant table's quantity, and the two used
to disagree about how large a number that may be — the cache being the smaller
one. A migration widened the column to match; the model was left saying the
old width. The table is gone and the records are the stock now, summed per
group by the records' view, so a record must hold what those sums can.

That gap does not show in production, where the column is what the migration
made it. It shows everywhere the schema is built from the model instead: the
test databases are narrower than the real one, so a quantity that a warehouse
can hold cannot be written in a test — and the next autogenerated migration
would offer to narrow production back down to the model's word.
"""

from __future__ import annotations

from decimal import Decimal

import pytest
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.item import Item
from app.models.storage_location import StorageLocation

pytestmark = pytest.mark.integration


class TestTheRecordAndTheQuantAgreeOnHowLarge:
    async def test_a_quantity_the_shelf_can_hold_fits_the_record(
        self,
        real_async_db_session: AsyncSession,
        async_test_storage_location: StorageLocation,
    ) -> None:
        """Above ten million: a warehouse of small parts reaches this."""
        db = real_async_db_session
        item = Item(
            name='Washers',
            organization_id=async_test_storage_location.organization_id,
            storage_location_id=async_test_storage_location.id,
            quantity=Decimal('12345678.900'),
        )
        db.add(item)
        await db.flush()

        stored = await db.scalar(select(Item.quantity).where(Item.id == item.id))
        assert stored == Decimal('12345678.900')

    async def test_an_ordinary_quantity_still_round_trips(
        self,
        real_async_db_session: AsyncSession,
        async_test_storage_location: StorageLocation,
    ) -> None:
        """The control: three decimals, as before."""
        db = real_async_db_session
        item = Item(
            name='Bolts',
            organization_id=async_test_storage_location.organization_id,
            storage_location_id=async_test_storage_location.id,
            quantity=Decimal('12.345'),
        )
        db.add(item)
        await db.flush()

        stored = await db.scalar(select(Item.quantity).where(Item.id == item.id))
        assert stored == Decimal('12.345')
