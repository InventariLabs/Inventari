/**
 * Scenario 1: Typical user (read-heavy)
 *
 * Simulates: browsing item list, searching, checking expiring items,
 * scanning barcodes, and viewing dashboard statistics.
 *
 * BEFORE running, seed test users and data:
 *   docker compose exec backend uv run python seed_load_test_users.py --count 100
 *   docker compose exec backend uv run python seed_load_test_data.py
 *
 * Run:
 *   docker compose -f docker-compose.loadtest.yml run --rm k6 \
 *     run /scenarios/browse_and_scan.js \
 *     -e BASE_URL=https://your-domain.com \
 *     --out influxdb=http://influxdb:8086/k6
 */
import http from 'k6/http';
import { sleep, check, group } from 'k6';
import { Trend, Rate } from 'k6/metrics';
import { SharedArray } from 'k6/data';
import { login, authHeaders, BASE_URL } from './auth.js';

// Custom metrics
const scanDuration = new Trend('scan_response_time', true);
const itemsListDuration = new Trend('items_list_response_time', true);
const errorRate = new Rate('error_rate');

// Load users from CSV (generated by seed_load_test_users.py)
// Each VU gets a different user from the list
const users = new SharedArray('users', function () {
  const csvPath = __ENV.USERS_CSV || '/users.csv';
  // parse CSV: email,password (skip header)
  return open(csvPath)
    .split('\n')
    .slice(1)
    .filter(Boolean)
    .map((line) => {
      const [email, password] = line.split(',');
      return { email: email.trim(), password: password.trim() };
    });
});

export const options = {
  stages: [
    { duration: '2m', target: 50 },   // warm-up
    { duration: '5m', target: 50 },   // steady state
    { duration: '2m', target: 100 },  // stress — find the limit
    { duration: '5m', target: 100 },
    { duration: '1m', target: 0 },    // ramp-down
  ],
  thresholds: {
    http_req_duration: ['p(95)<800'],
    error_rate: ['rate<0.01'],
    scan_response_time: ['p(95)<600'],
    items_list_response_time: ['p(95)<500'],
  },
};

// Realistic search queries matching data seeded by seed_load_test_data.py
const SEARCH_QUERIES = [
  'milk', 'bread', 'cheese', 'coffee', 'oil', 'yogurt', 'butter',
  'pasta', 'rice', 'flour', 'dumplings', 'ice cream', 'juice', 'tuna',
  'pizza', 'ham', 'sugar', 'tea', 'chocolate', 'carrot',
];

const BARCODES = [
  // Products seeded by seed_load_test_data.py (invented brands, EANs from
  // the restricted-circulation range 200-299)
  '2001000000012', // UHT milk
  '2001000000029', // Plain yogurt
  '2001000000036', // Butter
  '2003000000030', // Spaghetti pasta
  '2002000000071', // Frozen mixed vegetables
  '2003000000078', // Rolled oats
  '2003000000252', // Earl Grey tea
  '2003000000269', // Ground coffee
  '2003000000221', // Sardines in tomato sauce
  // Non-existent codes (tests 404 — expected behavior); their check digits
  // are wrong, so no product anywhere carries them
  '9999999999999', '1111111111111',
];

// Pagination values — tests OFFSET/LIMIT (the API's offset/limit params;
// it ignores an unknown `skip`, which used to leave every page at offset 0)
const OFFSET_VALUES = [0, 0, 0, 20, 40];  // more offset=0 (most common case)
const LIMIT_VALUES = [20, 50, 20, 20, 10];

// Init scope — runs once per VU before the test
// __VU is 1-based; each VU gets a unique user from the CSV
if (users.length === 0) {
  throw new Error(
    'users.csv is empty! Run first:\n' +
    '  docker compose exec backend uv run python seed_load_test_users.py --count 100'
  );
}
const vuUser = users[(__VU - 1) % users.length];
let vuToken = null;

export function setup() {}

export default function () {
  // First call — log in this VU
  if (!vuToken) {
    vuToken = login(vuUser.email, vuUser.password);
    if (!vuToken) {
      console.error(`VU ${__VU}: failed to log in as ${vuUser.email}`);
      sleep(5);
      return;
    }
  }
  const headers = authHeaders(vuToken);

  // Randomise offset/limit — simulates scrolling through pages
  const pageIdx = Math.floor(Math.random() * OFFSET_VALUES.length);
  const offset = OFFSET_VALUES[pageIdx];
  const limit = LIMIT_VALUES[pageIdx];

  group('Browse items with pagination', () => {
    const r = http.get(
      `${BASE_URL}/api/v1/items?offset=${offset}&limit=${limit}`,
      { headers, tags: { name: 'items/list' } }
    );
    itemsListDuration.add(r.timings.duration);
    const ok = check(r, { 'items 200': (res) => res.status === 200 });
    errorRate.add(!ok);
  });

  sleep(Math.random() * 2 + 0.5);

  group('Search by phrase', () => {
    const query = encodeURIComponent(SEARCH_QUERIES[Math.floor(Math.random() * SEARCH_QUERIES.length)]);
    const r = http.get(`${BASE_URL}/api/v1/items?search=${query}&offset=0&limit=20`, {
      headers,
      tags: { name: 'items/search' },
    });
    const ok = check(r, { 'search 200': (res) => res.status === 200 });
    errorRate.add(!ok);
  });

  sleep(Math.random() * 1.5 + 0.5);

  // Every 3rd iteration — check expiring items (heavier query: ORDER BY expiry_date)
  if (__ITER % 3 === 0) {
    group('Expiring items', () => {
      const r = http.get(`${BASE_URL}/api/v1/items/expiring`, {
        headers,
        tags: { name: 'items/expiring' },
      });
      check(r, { 'expiring 200': (res) => res.status === 200 });
    });
    sleep(Math.random() * 1);
  }

  group('Barcode scan', () => {
    const barcode = BARCODES[Math.floor(Math.random() * BARCODES.length)];
    const r = http.get(`${BASE_URL}/api/v1/labels/scan/${barcode}`, {
      headers,
      tags: { name: 'labels/scan' },
    });
    scanDuration.add(r.timings.duration);
    // 404 is OK — item may not be in the database
    const ok = check(r, { 'scan response': (res) => [200, 404].includes(res.status) });
    errorRate.add(!ok);
  });

  // Every 4th iteration — simulates opening the dashboard
  // These are the heaviest queries (GROUP BY, SUM, date math, ORDER BY)
  if (__ITER % 4 === 0) {
    group('Dashboard — overview stats', () => {
      const r = http.get(`${BASE_URL}/api/v1/stats/overview`, {
        headers,
        tags: { name: 'stats/overview' },
      });
      check(r, { 'overview 200': (res) => res.status === 200 });
    });

    sleep(Math.random() * 1 + 0.5);

    // Stats by storage location — JOIN + GROUP BY location
    group('Stats by storage', () => {
      const r = http.get(`${BASE_URL}/api/v1/stats/by-location`, {
        headers,
        tags: { name: 'stats/by-location' },
      });
      check(r, { 'by-storage 200': (res) => res.status === 200 });
    });

    sleep(Math.random() * 0.5);
  }

  // Every 6th iteration — expiry forecast (heavy GROUP BY date)
  if (__ITER % 6 === 0) {
    group('Expiry forecast', () => {
      const r = http.get(`${BASE_URL}/api/v1/stats/expiry-forecast`, {
        headers,
        tags: { name: 'stats/expiry-forecast' },
      });
      check(r, { 'expiry-forecast 200': (res) => res.status === 200 });
    });

    sleep(Math.random() * 0.5);
  }

  // Every 8th iteration — rotation analysis (heaviest: full history scan)
  if (__ITER % 8 === 0) {
    group('Rotation analysis', () => {
      const r = http.get(`${BASE_URL}/api/v1/stats/rotation-analysis`, {
        headers,
        tags: { name: 'stats/rotation-analysis' },
      });
      check(r, { 'rotation 200': (res) => [200, 404].includes(res.status) });
    });

    sleep(Math.random() * 0.5);
  }

  sleep(Math.random() * 3 + 2); // natural pause between "clicks"
}

export function teardown() {
  console.log(`✅ browse_and_scan finished. Used ${users.length} unique users.`);
}
